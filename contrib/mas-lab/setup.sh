#!/usr/bin/env bash
# Builds the Dendrite image from this checkout and generates the configuration of the lab
# into ./generated (not committed). REGENERATE=1 starts over with new secrets.
set -eu
cd "$(dirname "$0")"
IMAGE=${DENDRITE_IMAGE:-dendrite-lab:local}
MAS_IMAGE=ghcr.io/element-hq/matrix-authentication-service:1.29.0
SERVER_NAME=lab.test

docker build -q -t "$IMAGE" ../.. >/dev/null
if [ -d generated ] && [ "${REGENERATE:-0}" != 1 ]; then exit 0; fi
rm -rf generated
mkdir -p generated/dendrite
SECRET=$(head -c 24 /dev/urandom | base64 | tr -d '/+=' | head -c 32)
echo "$SECRET" > generated/secret.txt

# Dendrite: keys and a configuration generated by the binaries of the image.
docker run --rm --user "$(id -u):$(id -g)" --entrypoint /bin/sh -v "$PWD/generated/dendrite:/etc/dendrite" "$IMAGE" -c \
  "/usr/bin/generate-keys --private-key /etc/dendrite/matrix_key.pem >/dev/null && \
   /usr/bin/generate-config -dir /var/dendrite -db 'postgresql://dendrite:dendrite@postgres/dendrite?sslmode=disable' -server $SERVER_NAME > /etc/dendrite/dendrite.yaml"
chmod 644 generated/dendrite/matrix_key.pem

cat > generated/dendrite/appservice-bridge.yaml <<AS
id: bridge
url: ""
as_token: lab_as_token_0123456789
hs_token: lab_hs_token_0123456789
sender_localpart: bridgebot
rate_limited: false
namespaces:
  users:
    - exclusive: true
      regex: "@bridge_.*:$SERVER_NAME"
  aliases: []
  rooms: []
AS

# The generated file already has msc3861 and rendezvous blocks (disabled). Edit them, a second
# block with the same key would silently win or lose.
perl -0pi -e "s/(  msc3861:\n    enabled: )false(\n    issuer: )\"\"(\n    client_id: \"\"\n    client_secret: \"\"\n    client_auth_method: \"\"\n    shared_secret: )\"\"/\${1}true\${2}\"http:\/\/mas:8080\/\"\${3}\"$SECRET\"/; s/(  rendezvous:\n    enabled: )false(\n    allow_unauthenticated: )false/\${1}true\${2}true/; s/well_known_client_name: \"\"/well_known_client_name: \"http:\/\/dendrite:8008\"/; s/config_files: \[\]/config_files:\n    - \/etc\/dendrite\/appservice-bridge.yaml/; s/(rate_limiting:\n    enabled: )true/\${1}false/; s/(  url_previews:\n    enabled: )false/\${1}true/" generated/dendrite/dendrite.yaml
grep -q "shared_secret: \"$SECRET\"" generated/dendrite/dendrite.yaml || { echo "could not enable msc3861 in the generated Dendrite config" >&2; exit 1; }

# MAS: the generated secrets and our settings.
docker run --rm "$MAS_IMAGE" config generate > generated/mas-generated.yaml 2>/dev/null
cat > generated/mas.yaml <<MAS
http:
  listeners:
  - name: web
    resources:
    - name: discovery
    - name: human
    - name: oauth
    - name: compat
    - name: graphql
    - name: assets
    binds:
    - address: '0.0.0.0:8080'
  - name: internal
    resources:
    - name: health
    binds:
    - address: '0.0.0.0:8081'
  public_base: http://mas:8080/
  issuer: http://mas:8080/
database:
  uri: postgresql://mas:mas@postgres/mas
email:
  from: '"Authentication Service" <root@localhost>'
  reply_to: '"Authentication Service" <root@localhost>'
  transport: blackhole
passwords:
  enabled: true
  schemes:
  - version: 1
    algorithm: argon2id
  minimum_complexity: 0
matrix:
  kind: synapse
  homeserver: $SERVER_NAME
  secret: $SECRET
  endpoint: http://dendrite:8008/
rate_limiting:
  login:
    per_ip: {burst: 1000, per_second: 1000}
    per_account: {burst: 1000, per_second: 1000}
MAS
sed -n '/^secrets:/,/^passwords:/p' generated/mas-generated.yaml | sed '$d' >> generated/mas.yaml
